-- =====================================================================
-- SQL Performance & Tuning (SPT) - core schema - ORACLE (19c+)
--
-- Drill path (up <-> down):
--   SPT_TUNING_TRACKER (1) -- (1) SPT_QUERY_GROUP (1) -- (n) SPT_QUERY_LOG
--   SPT_INGESTION_BATCH (1) -- (n) SPT_QUERY_LOG
--
-- Workflow tables (see docs/architecture.md, numbers match the diagram):
--   SPT_SQL_DIAGNOSTIC   steps 4,5,6,10  explain / profile / exec summary
--   SPT_TABLE_DDL        step 8          DDL + row counts fed to the agent
--   SPT_PROMPT_TEMPLATE  step 7          versioned optimization prompts
--   SPT_OPTIMIZATION_RUN steps 8,9       agent input/output
--   SPT_FEEDBACK         step 12 + note  adoption / rejection feedback
--
-- Extensibility: SPT_CUSTOM_FIELD / SPT_CUSTOM_FIELD_VALUE add business
-- columns at runtime without DDL. Promote a custom field to a real column
-- with a new Flyway migration once it is stable.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Source connections used to pull query logs (Oracle / Impala / JDBC)
-- ---------------------------------------------------------------------
CREATE TABLE SPT_DATA_SOURCE (
    ID              NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    NAME            VARCHAR2(100)   NOT NULL,
    SOURCE_TYPE     VARCHAR2(20)    NOT NULL,
    SQL_ENGINE      VARCHAR2(20)    DEFAULT 'IMPALA' NOT NULL,
    JDBC_URL        VARCHAR2(1000)  NOT NULL,
    DRIVER_CLASS    VARCHAR2(200),
    USERNAME        VARCHAR2(200),
    PASSWORD_REF    VARCHAR2(200),
    LOG_QUERY       CLOB            NOT NULL,
    FETCH_SIZE      NUMBER(10)      DEFAULT 1000 NOT NULL,
    LAST_WATERMARK  TIMESTAMP,
    ACTIVE          NUMBER(1)       DEFAULT 1 NOT NULL,
    DESCRIPTION     VARCHAR2(1000),
    CREATED_AT      TIMESTAMP       NOT NULL,
    CREATED_BY      VARCHAR2(100),
    UPDATED_AT      TIMESTAMP,
    UPDATED_BY      VARCHAR2(100),
    VERSION         NUMBER(10)      DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SPT_DATA_SOURCE PRIMARY KEY (ID),
    CONSTRAINT UK_SPT_DATA_SOURCE_NAME UNIQUE (NAME),
    CONSTRAINT CK_SPT_DS_TYPE CHECK (SOURCE_TYPE IN ('ORACLE', 'IMPALA', 'GENERIC_JDBC')),
    CONSTRAINT CK_SPT_DS_ACTIVE CHECK (ACTIVE IN (0, 1))
);
COMMENT ON COLUMN SPT_DATA_SOURCE.PASSWORD_REF IS 'Name of an environment variable / Spring property holding the password. Plain-text passwords are never stored.';
COMMENT ON COLUMN SPT_DATA_SOURCE.LOG_QUERY IS 'SELECT returning the standard log columns (SEQ_ID, EXECUTED_QUERY, ...). May reference :since for incremental pulls.';

-- ---------------------------------------------------------------------
-- One row per import (file upload or JDBC pull)
-- ---------------------------------------------------------------------
CREATE TABLE SPT_INGESTION_BATCH (
    ID              NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    SOURCE_KIND     VARCHAR2(20)    NOT NULL,
    DATA_SOURCE_ID  NUMBER(19),
    SOURCE_NAME     VARCHAR2(500),
    SQL_ENGINE      VARCHAR2(20)    NOT NULL,
    STATUS          VARCHAR2(30)    NOT NULL,
    ROWS_READ       NUMBER(10)      DEFAULT 0 NOT NULL,
    ROWS_LOADED     NUMBER(10)      DEFAULT 0 NOT NULL,
    ROWS_REJECTED   NUMBER(10)      DEFAULT 0 NOT NULL,
    GROUPS_AFFECTED NUMBER(10)      DEFAULT 0 NOT NULL,
    MESSAGE         VARCHAR2(4000),
    STARTED_AT      TIMESTAMP       NOT NULL,
    COMPLETED_AT    TIMESTAMP,
    CREATED_BY      VARCHAR2(100),
    CONSTRAINT PK_SPT_INGESTION_BATCH PRIMARY KEY (ID),
    CONSTRAINT FK_SPT_BATCH_DS FOREIGN KEY (DATA_SOURCE_ID) REFERENCES SPT_DATA_SOURCE (ID),
    CONSTRAINT CK_SPT_BATCH_KIND CHECK (SOURCE_KIND IN ('CSV', 'EXCEL', 'JDBC')),
    CONSTRAINT CK_SPT_BATCH_STATUS CHECK (STATUS IN ('RUNNING', 'COMPLETED', 'COMPLETED_WITH_ERRORS', 'FAILED'))
);

-- ---------------------------------------------------------------------
-- Groups of equivalent SQL (same fingerprint = same SQL minus WHERE part)
-- ---------------------------------------------------------------------
CREATE TABLE SPT_QUERY_GROUP (
    ID                    NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    FINGERPRINT           VARCHAR2(64)    NOT NULL,
    SQL_ENGINE            VARCHAR2(20)    NOT NULL,
    GROUP_SIZE            NUMBER(10)      DEFAULT 0 NOT NULL,
    DISTINCT_USERS        NUMBER(10)      DEFAULT 0 NOT NULL,
    USER_IDS              VARCHAR2(4000),
    DURATION_COUNT        NUMBER(10)      DEFAULT 0 NOT NULL,
    AVG_DURATION_MINUTES  NUMBER(14,4),
    MIN_DURATION_MINUTES  NUMBER(14,4),
    MAX_DURATION_MINUTES  NUMBER(14,4),
    TOTAL_DURATION_MINUTES NUMBER(16,4),
    ERROR_COUNT           NUMBER(10)      DEFAULT 0 NOT NULL,
    SAMPLE_LOG_ID         NUMBER(19),
    SAMPLE_QUERY_SEQ_ID   NUMBER(19),
    SAMPLE_QUERY          CLOB,
    NORMALIZED_QUERY      CLOB,
    ROW_INDICES           CLOB,
    FIRST_SEEN            TIMESTAMP,
    LAST_SEEN             TIMESTAMP,
    CREATED_AT            TIMESTAMP       NOT NULL,
    UPDATED_AT            TIMESTAMP,
    VERSION               NUMBER(10)      DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SPT_QUERY_GROUP PRIMARY KEY (ID),
    CONSTRAINT UK_SPT_GROUP_FP UNIQUE (SQL_ENGINE, FINGERPRINT)
);
COMMENT ON COLUMN SPT_QUERY_GROUP.FINGERPRINT IS 'SHA-256 of the normalized SQL (comments, literals and WHERE clauses removed).';
COMMENT ON COLUMN SPT_QUERY_GROUP.ROW_INDICES IS 'Comma separated SEQ_IDs of the member log rows.';
COMMENT ON COLUMN SPT_QUERY_GROUP.SAMPLE_LOG_ID IS 'Longest running member - the "bad SQL" candidate.';
CREATE INDEX IX_SPT_GROUP_TOTAL_DUR ON SPT_QUERY_GROUP (TOTAL_DURATION_MINUTES);

-- ---------------------------------------------------------------------
-- Raw query log rows (input file / source table)
-- ---------------------------------------------------------------------
CREATE TABLE SPT_QUERY_LOG (
    ID                NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    BATCH_ID          NUMBER(19)      NOT NULL,
    SEQ_ID            NUMBER(19),
    EXECUTED_QUERY    CLOB,
    USER_QUERY        CLOB,
    ERROR_CODE        VARCHAR2(100),
    ERROR_CATEGORY    VARCHAR2(200),
    ERROR_MESSAGE     CLOB,
    USER_ID           VARCHAR2(200),
    START_TIME        TIMESTAMP,
    END_TIME          TIMESTAMP,
    DURATION_MINUTES  NUMBER(14,4),
    SQL_ENGINE        VARCHAR2(20)    NOT NULL,
    FINGERPRINT       VARCHAR2(64),
    GROUP_ID          NUMBER(19),
    CREATED_AT        TIMESTAMP       NOT NULL,
    CONSTRAINT PK_SPT_QUERY_LOG PRIMARY KEY (ID),
    CONSTRAINT FK_SPT_LOG_BATCH FOREIGN KEY (BATCH_ID) REFERENCES SPT_INGESTION_BATCH (ID),
    CONSTRAINT FK_SPT_LOG_GROUP FOREIGN KEY (GROUP_ID) REFERENCES SPT_QUERY_GROUP (ID)
);
CREATE INDEX IX_SPT_LOG_GROUP ON SPT_QUERY_LOG (GROUP_ID);
CREATE INDEX IX_SPT_LOG_FP ON SPT_QUERY_LOG (SQL_ENGINE, FINGERPRINT);
CREATE INDEX IX_SPT_LOG_BATCH ON SPT_QUERY_LOG (BATCH_ID);
CREATE INDEX IX_SPT_LOG_USER ON SPT_QUERY_LOG (USER_ID);
CREATE INDEX IX_SPT_LOG_START ON SPT_QUERY_LOG (START_TIME);
CREATE INDEX IX_SPT_LOG_SEQ ON SPT_QUERY_LOG (SEQ_ID);

-- ---------------------------------------------------------------------
-- Tuning tracker: one row per group that is being worked on
-- (group metrics are read live from SPT_QUERY_GROUP, see SPT_TRACKER_V)
-- ---------------------------------------------------------------------
CREATE TABLE SPT_TUNING_TRACKER (
    ID                              NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    GROUP_ID                        NUMBER(19)      NOT NULL,
    WORKFLOW_STATUS                 VARCHAR2(40)    DEFAULT 'NEW' NOT NULL,
    PRIORITY                        VARCHAR2(20)    DEFAULT 'MEDIUM' NOT NULL,
    SAMPLE_QUERY_FORMATTED          CLOB,
    CLEANSED_QUERY                  CLOB,
    OPTIMIZED_QUERY                 CLOB,
    DEV_TEAM_LEAD                   VARCHAR2(200),
    DEV_TEAM_STATUS                 VARCHAR2(100),
    CLOUDERA_TEAM_LEAD              VARCHAR2(200),
    SME_TEAM_LEAD                   VARCHAR2(200),
    OPTIMIZED_SQL_STATUS            VARCHAR2(100),
    CLOUDERA_POST_RUN_VALIDATION    VARCHAR2(100),
    OG_RUN_DURATION_MINUTES         NUMBER(14,4),
    POST_RUN_DURATION_MINUTES       NUMBER(14,4),
    OG_EXECUTION_TIME_SECONDS       NUMBER(14,4),
    POST_RUN_EXECUTION_TIME_SECONDS NUMBER(14,4),
    OG_TEARDOWN_TIME_SECONDS        NUMBER(14,4),
    POST_RUN_TEARDOWN_TIME_SECONDS  NUMBER(14,4),
    OG_TEARDOWN_PCT                 NUMBER(7,3),
    POST_RUN_TEARDOWN_PCT           NUMBER(7,3),
    THEME                           VARCHAR2(200),
    SME_VALIDATION                  VARCHAR2(100),
    INSTALL_STATUS                  VARCHAR2(100),
    EXECUTE_STATUS                  VARCHAR2(100),
    VALIDATION_STATUS               VARCHAR2(100),
    CHANGES                         CLOB,
    PROBLEM                         CLOB,
    RECOMMENDATIONS                 CLOB,
    CREATED_AT                      TIMESTAMP       NOT NULL,
    CREATED_BY                      VARCHAR2(100),
    UPDATED_AT                      TIMESTAMP,
    UPDATED_BY                      VARCHAR2(100),
    VERSION                         NUMBER(10)      DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SPT_TUNING_TRACKER PRIMARY KEY (ID),
    CONSTRAINT UK_SPT_TRACKER_GROUP UNIQUE (GROUP_ID),
    CONSTRAINT FK_SPT_TRACKER_GROUP FOREIGN KEY (GROUP_ID) REFERENCES SPT_QUERY_GROUP (ID),
    CONSTRAINT CK_SPT_TRACKER_PRIORITY CHECK (PRIORITY IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL'))
);
CREATE INDEX IX_SPT_TRACKER_STATUS ON SPT_TUNING_TRACKER (WORKFLOW_STATUS);

-- ---------------------------------------------------------------------
-- Diagnostics captured by the SQL Diagnostic Tool (before / after)
-- ---------------------------------------------------------------------
CREATE TABLE SPT_SQL_DIAGNOSTIC (
    ID                    NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    GROUP_ID              NUMBER(19)      NOT NULL,
    PHASE                 VARCHAR2(20)    NOT NULL,
    OPTIMIZATION_RUN_ID   NUMBER(19),
    QUERY_ID              VARCHAR2(100),
    SQL_TEXT              CLOB,
    ROW_COUNT             NUMBER(19),
    RUN_DURATION_SECONDS  NUMBER(14,4),
    EXPLAIN_PLAN          CLOB,
    PROFILE_RAW           CLOB,
    PROFILE_SUMMARY       CLOB,
    EXEC_SUMMARY          CLOB,
    STATUS                VARCHAR2(20)    NOT NULL,
    ERROR_MESSAGE         CLOB,
    CAPTURED_AT           TIMESTAMP       NOT NULL,
    CAPTURED_BY           VARCHAR2(100),
    CONSTRAINT PK_SPT_SQL_DIAGNOSTIC PRIMARY KEY (ID),
    CONSTRAINT FK_SPT_DIAG_GROUP FOREIGN KEY (GROUP_ID) REFERENCES SPT_QUERY_GROUP (ID),
    CONSTRAINT CK_SPT_DIAG_PHASE CHECK (PHASE IN ('ORIGINAL', 'OPTIMIZED')),
    CONSTRAINT CK_SPT_DIAG_STATUS CHECK (STATUS IN ('CAPTURED', 'FAILED', 'TIMEOUT'))
);
COMMENT ON COLUMN SPT_SQL_DIAGNOSTIC.PROFILE_SUMMARY IS 'JSON produced by the profile parser (step 6) - compact input for the LLM.';
CREATE INDEX IX_SPT_DIAG_GROUP ON SPT_SQL_DIAGNOSTIC (GROUP_ID, PHASE);

CREATE TABLE SPT_TABLE_DDL (
    ID          NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    GROUP_ID    NUMBER(19)      NOT NULL,
    TABLE_NAME  VARCHAR2(300)   NOT NULL,
    DDL_TEXT    CLOB,
    ROW_COUNT   NUMBER(19),
    CAPTURED_AT TIMESTAMP       NOT NULL,
    CAPTURED_BY VARCHAR2(100),
    CONSTRAINT PK_SPT_TABLE_DDL PRIMARY KEY (ID),
    CONSTRAINT FK_SPT_DDL_GROUP FOREIGN KEY (GROUP_ID) REFERENCES SPT_QUERY_GROUP (ID)
);
CREATE INDEX IX_SPT_DDL_GROUP ON SPT_TABLE_DDL (GROUP_ID);

-- ---------------------------------------------------------------------
-- Optimization agent (prompts, runs) and feedback loop
-- ---------------------------------------------------------------------
CREATE TABLE SPT_PROMPT_TEMPLATE (
    ID            NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    NAME          VARCHAR2(100)   NOT NULL,
    SQL_ENGINE    VARCHAR2(20)    NOT NULL,
    VERSION_NO    NUMBER(5)       NOT NULL,
    TEMPLATE_TEXT CLOB            NOT NULL,
    ACTIVE        NUMBER(1)       DEFAULT 1 NOT NULL,
    NOTES         VARCHAR2(2000),
    CREATED_AT    TIMESTAMP       NOT NULL,
    CREATED_BY    VARCHAR2(100),
    CONSTRAINT PK_SPT_PROMPT_TEMPLATE PRIMARY KEY (ID),
    CONSTRAINT UK_SPT_PROMPT_VER UNIQUE (NAME, VERSION_NO),
    CONSTRAINT CK_SPT_PROMPT_ACTIVE CHECK (ACTIVE IN (0, 1))
);

CREATE TABLE SPT_OPTIMIZATION_RUN (
    ID                  NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    GROUP_ID            NUMBER(19)      NOT NULL,
    PROMPT_TEMPLATE_ID  NUMBER(19),
    MODEL_NAME          VARCHAR2(100),
    PROMPT_TEXT         CLOB,
    RESPONSE_RAW        CLOB,
    CHANGE_NARRATIVE    CLOB,
    OPTIMIZED_SQL       CLOB,
    STATUS              VARCHAR2(20)    NOT NULL,
    OUTCOME             VARCHAR2(20),
    ERROR_MESSAGE       CLOB,
    REQUESTED_AT        TIMESTAMP       NOT NULL,
    COMPLETED_AT        TIMESTAMP,
    REQUESTED_BY        VARCHAR2(100),
    CONSTRAINT PK_SPT_OPTIMIZATION_RUN PRIMARY KEY (ID),
    CONSTRAINT FK_SPT_OPT_GROUP FOREIGN KEY (GROUP_ID) REFERENCES SPT_QUERY_GROUP (ID),
    CONSTRAINT FK_SPT_OPT_PROMPT FOREIGN KEY (PROMPT_TEMPLATE_ID) REFERENCES SPT_PROMPT_TEMPLATE (ID),
    CONSTRAINT CK_SPT_OPT_STATUS CHECK (STATUS IN ('PENDING', 'COMPLETED', 'FAILED')),
    CONSTRAINT CK_SPT_OPT_OUTCOME CHECK (OUTCOME IS NULL OR OUTCOME IN ('ACCEPTED', 'REJECTED'))
);
CREATE INDEX IX_SPT_OPT_GROUP ON SPT_OPTIMIZATION_RUN (GROUP_ID);

ALTER TABLE SPT_SQL_DIAGNOSTIC ADD CONSTRAINT FK_SPT_DIAG_OPT
    FOREIGN KEY (OPTIMIZATION_RUN_ID) REFERENCES SPT_OPTIMIZATION_RUN (ID);

CREATE TABLE SPT_FEEDBACK (
    ID                  NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    GROUP_ID            NUMBER(19)      NOT NULL,
    OPTIMIZATION_RUN_ID NUMBER(19),
    SOURCE_ROLE         VARCHAR2(30)    NOT NULL,
    DECISION            VARCHAR2(20)    NOT NULL,
    COMMENTS            CLOB,
    CREATED_AT          TIMESTAMP       NOT NULL,
    CREATED_BY          VARCHAR2(100),
    CONSTRAINT PK_SPT_FEEDBACK PRIMARY KEY (ID),
    CONSTRAINT FK_SPT_FB_GROUP FOREIGN KEY (GROUP_ID) REFERENCES SPT_QUERY_GROUP (ID),
    CONSTRAINT FK_SPT_FB_OPT FOREIGN KEY (OPTIMIZATION_RUN_ID) REFERENCES SPT_OPTIMIZATION_RUN (ID),
    CONSTRAINT CK_SPT_FB_ROLE CHECK (SOURCE_ROLE IN ('BUSINESS_USER', 'CLIENT_DEV', 'CLOUDERA', 'SME')),
    CONSTRAINT CK_SPT_FB_DECISION CHECK (DECISION IN ('ADOPTED', 'REJECTED', 'COMMENT'))
);
CREATE INDEX IX_SPT_FB_GROUP ON SPT_FEEDBACK (GROUP_ID);

-- ---------------------------------------------------------------------
-- Runtime-extensible columns
-- ---------------------------------------------------------------------
CREATE TABLE SPT_CUSTOM_FIELD (
    ID            NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    ENTITY_TYPE   VARCHAR2(30)    NOT NULL,
    FIELD_KEY     VARCHAR2(100)   NOT NULL,
    LABEL         VARCHAR2(200)   NOT NULL,
    DATA_TYPE     VARCHAR2(20)    NOT NULL,
    OPTIONS_CSV   VARCHAR2(4000),
    DISPLAY_ORDER NUMBER(5)       DEFAULT 0 NOT NULL,
    REQUIRED      NUMBER(1)       DEFAULT 0 NOT NULL,
    ACTIVE        NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT    TIMESTAMP       NOT NULL,
    CREATED_BY    VARCHAR2(100),
    CONSTRAINT PK_SPT_CUSTOM_FIELD PRIMARY KEY (ID),
    CONSTRAINT UK_SPT_CF_KEY UNIQUE (ENTITY_TYPE, FIELD_KEY),
    CONSTRAINT CK_SPT_CF_ENTITY CHECK (ENTITY_TYPE IN ('TRACKER', 'GROUP', 'LOG')),
    CONSTRAINT CK_SPT_CF_TYPE CHECK (DATA_TYPE IN ('TEXT', 'LONG_TEXT', 'NUMBER', 'DATE', 'BOOLEAN', 'ENUM'))
);

CREATE TABLE SPT_CUSTOM_FIELD_VALUE (
    ID          NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    FIELD_ID    NUMBER(19)      NOT NULL,
    ENTITY_ID   NUMBER(19)      NOT NULL,
    VALUE_TEXT  VARCHAR2(4000),
    UPDATED_AT  TIMESTAMP       NOT NULL,
    UPDATED_BY  VARCHAR2(100),
    CONSTRAINT PK_SPT_CUSTOM_FIELD_VALUE PRIMARY KEY (ID),
    CONSTRAINT UK_SPT_CFV UNIQUE (FIELD_ID, ENTITY_ID),
    CONSTRAINT FK_SPT_CFV_FIELD FOREIGN KEY (FIELD_ID) REFERENCES SPT_CUSTOM_FIELD (ID) ON DELETE CASCADE
);
CREATE INDEX IX_SPT_CFV_ENTITY ON SPT_CUSTOM_FIELD_VALUE (ENTITY_ID);

-- ---------------------------------------------------------------------
-- Field-level change history (tracker edits, workflow transitions)
-- ---------------------------------------------------------------------
CREATE TABLE SPT_AUDIT_EVENT (
    ID          NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    ENTITY_TYPE VARCHAR2(30)    NOT NULL,
    ENTITY_ID   NUMBER(19)      NOT NULL,
    ACTION      VARCHAR2(20)    NOT NULL,
    FIELD_NAME  VARCHAR2(100),
    OLD_VALUE   VARCHAR2(4000),
    NEW_VALUE   VARCHAR2(4000),
    CHANGED_AT  TIMESTAMP       NOT NULL,
    CHANGED_BY  VARCHAR2(100),
    CONSTRAINT PK_SPT_AUDIT_EVENT PRIMARY KEY (ID)
);
CREATE INDEX IX_SPT_AUDIT_ENTITY ON SPT_AUDIT_EVENT (ENTITY_TYPE, ENTITY_ID);

-- ---------------------------------------------------------------------
-- Reporting view: tracking screen = tracker + live group metrics
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW SPT_TRACKER_V AS
SELECT t.ID                         AS TRACKER_ID,
       g.ID                         AS GROUP_ID,
       g.GROUP_SIZE,
       g.DISTINCT_USERS,
       g.FINGERPRINT,
       g.AVG_DURATION_MINUTES,
       g.MIN_DURATION_MINUTES,
       g.MAX_DURATION_MINUTES,
       g.TOTAL_DURATION_MINUTES,
       g.SAMPLE_QUERY_SEQ_ID,
       g.SAMPLE_QUERY               AS SAMPLE_QUERY_RAW,
       t.SAMPLE_QUERY_FORMATTED,
       g.ROW_INDICES,
       t.CLEANSED_QUERY,
       t.OPTIMIZED_QUERY,
       t.DEV_TEAM_LEAD,
       t.DEV_TEAM_STATUS,
       t.CLOUDERA_TEAM_LEAD,
       t.SME_TEAM_LEAD,
       t.OPTIMIZED_SQL_STATUS,
       t.CLOUDERA_POST_RUN_VALIDATION,
       t.OG_RUN_DURATION_MINUTES,
       t.POST_RUN_DURATION_MINUTES,
       t.OG_EXECUTION_TIME_SECONDS,
       t.POST_RUN_EXECUTION_TIME_SECONDS,
       t.OG_TEARDOWN_TIME_SECONDS,
       t.POST_RUN_TEARDOWN_TIME_SECONDS,
       t.OG_TEARDOWN_PCT,
       t.POST_RUN_TEARDOWN_PCT,
       t.THEME,
       t.SME_VALIDATION,
       t.INSTALL_STATUS,
       t.EXECUTE_STATUS,
       t.VALIDATION_STATUS,
       t.CHANGES,
       t.PROBLEM,
       t.RECOMMENDATIONS,
       t.WORKFLOW_STATUS,
       t.PRIORITY,
       t.UPDATED_AT,
       t.UPDATED_BY
  FROM SPT_TUNING_TRACKER t
  JOIN SPT_QUERY_GROUP g ON g.ID = t.GROUP_ID;
