-- =====================================================================
-- V4: analytics & tuning iterations
--   SPT_LOOKUP               admin-editable dropdown values (themes, statuses, reasons, ...)
--   SPT_TUNING_ITERATION     every tuning attempt of a tracker item with its test metrics;
--                            the best one is selected, then adopted (or rejected)
--   SPT_USER_DIRECTORY       user -> user group / department (bad queries by user group)
--   SPT_TUNING_TRACKER       request source (log / proactive UAT / user request), stage
--                            timestamps for turnaround, CPU / rows / tables metrics
--   SPT_SQL_DIAGNOSTIC       iteration link + parsed CPU / rows / tables metrics
--   SPT_FEEDBACK             iteration link + rejection reason
-- =====================================================================

CREATE TABLE SPT_LOOKUP (
    ID            NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    CATEGORY      VARCHAR2(50)    NOT NULL,
    LOOKUP_VALUE  VARCHAR2(200)   NOT NULL,
    SORT_ORDER    NUMBER(5)       DEFAULT 0 NOT NULL,
    TONE          VARCHAR2(20),
    ACTIVE        NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT    TIMESTAMP       NOT NULL,
    CONSTRAINT PK_SPT_LOOKUP PRIMARY KEY (ID),
    CONSTRAINT UK_SPT_LOOKUP UNIQUE (CATEGORY, LOOKUP_VALUE),
    CONSTRAINT CK_SPT_LOOKUP_ACTIVE CHECK (ACTIVE IN (0, 1))
);
COMMENT ON COLUMN SPT_LOOKUP.TONE IS 'Chip colour hint for the UI: ok, warn, bad, info, muted.';

ALTER TABLE SPT_TUNING_TRACKER ADD (
    REQUEST_SOURCE           VARCHAR2(30)    DEFAULT 'LOG_DETECTED' NOT NULL,
    REQUESTED_BY             VARCHAR2(200),
    ENVIRONMENT              VARCHAR2(30),
    STAGE_CHANGED_AT         TIMESTAMP,
    ADOPTED_AT               TIMESTAMP,
    CLOSED_AT                TIMESTAMP,
    SELECTED_ITERATION_ID    NUMBER(19),
    OG_CPU_SECONDS           NUMBER(16,4),
    POST_RUN_CPU_SECONDS     NUMBER(16,4),
    OG_ROWS_SCANNED          NUMBER(19),
    POST_RUN_ROWS_SCANNED    NUMBER(19),
    OG_TABLES_SCANNED        NUMBER(10),
    POST_RUN_TABLES_SCANNED  NUMBER(10),
    OG_BYTES_SCANNED         NUMBER(19),
    POST_RUN_BYTES_SCANNED   NUMBER(19),
    OG_PEAK_MEMORY_MB        NUMBER(14,2),
    POST_RUN_PEAK_MEMORY_MB  NUMBER(14,2)
);
ALTER TABLE SPT_TUNING_TRACKER ADD CONSTRAINT CK_SPT_TRACKER_SOURCE
    CHECK (REQUEST_SOURCE IN ('LOG_DETECTED', 'PROACTIVE_UAT', 'USER_REQUEST'));
UPDATE SPT_TUNING_TRACKER SET STAGE_CHANGED_AT = COALESCE(UPDATED_AT, CREATED_AT);
UPDATE SPT_TUNING_TRACKER SET ADOPTED_AT = COALESCE(UPDATED_AT, CREATED_AT), CLOSED_AT = COALESCE(UPDATED_AT, CREATED_AT)
 WHERE WORKFLOW_STATUS = 'ADOPTED';
UPDATE SPT_TUNING_TRACKER SET CLOSED_AT = COALESCE(UPDATED_AT, CREATED_AT) WHERE WORKFLOW_STATUS = 'REJECTED';
CREATE INDEX IX_SPT_TRACKER_ADOPTED ON SPT_TUNING_TRACKER (ADOPTED_AT);
CREATE INDEX IX_SPT_TRACKER_THEME ON SPT_TUNING_TRACKER (THEME);
CREATE INDEX IX_SPT_GROUP_FIRST_SEEN ON SPT_QUERY_GROUP (FIRST_SEEN);

CREATE TABLE SPT_TUNING_ITERATION (
    ID                      NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    TRACKER_ID              NUMBER(19)      NOT NULL,
    ITERATION_NO            NUMBER(5)       NOT NULL,
    SOURCE                  VARCHAR2(20)    NOT NULL,
    OPTIMIZATION_RUN_ID     NUMBER(19),
    OPTIMIZED_SQL           CLOB,
    CHANGE_NARRATIVE        CLOB,
    STATUS                  VARCHAR2(20)    NOT NULL,
    RUN_DURATION_MINUTES    NUMBER(14,4),
    EXECUTION_TIME_SECONDS  NUMBER(14,4),
    TEARDOWN_TIME_SECONDS   NUMBER(14,4),
    CPU_SECONDS             NUMBER(16,4),
    ROWS_SCANNED            NUMBER(19),
    BYTES_SCANNED           NUMBER(19),
    TABLES_SCANNED          NUMBER(10),
    PEAK_MEMORY_MB          NUMBER(14,2),
    RESULT_ROW_COUNT        NUMBER(19),
    RESULT_MATCHES          NUMBER(1),
    NOTES                   CLOB,
    TESTED_AT               TIMESTAMP,
    TESTED_BY               VARCHAR2(100),
    CREATED_AT              TIMESTAMP       NOT NULL,
    CREATED_BY              VARCHAR2(100),
    UPDATED_AT              TIMESTAMP,
    VERSION                 NUMBER(10)      DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SPT_TUNING_ITERATION PRIMARY KEY (ID),
    CONSTRAINT UK_SPT_ITERATION_NO UNIQUE (TRACKER_ID, ITERATION_NO),
    CONSTRAINT FK_SPT_ITER_TRACKER FOREIGN KEY (TRACKER_ID) REFERENCES SPT_TUNING_TRACKER (ID),
    CONSTRAINT FK_SPT_ITER_RUN FOREIGN KEY (OPTIMIZATION_RUN_ID) REFERENCES SPT_OPTIMIZATION_RUN (ID),
    CONSTRAINT CK_SPT_ITER_SOURCE CHECK (SOURCE IN ('AI_AGENT', 'MANUAL')),
    CONSTRAINT CK_SPT_ITER_STATUS CHECK (STATUS IN ('PROPOSED', 'TESTED', 'FAILED', 'SELECTED', 'ADOPTED', 'REJECTED')),
    CONSTRAINT CK_SPT_ITER_MATCH CHECK (RESULT_MATCHES IS NULL OR RESULT_MATCHES IN (0, 1))
);
CREATE INDEX IX_SPT_ITER_TRACKER ON SPT_TUNING_ITERATION (TRACKER_ID);
ALTER TABLE SPT_TUNING_TRACKER ADD CONSTRAINT FK_SPT_TRACKER_ITER
    FOREIGN KEY (SELECTED_ITERATION_ID) REFERENCES SPT_TUNING_ITERATION (ID);

ALTER TABLE SPT_SQL_DIAGNOSTIC ADD (
    ITERATION_ID            NUMBER(19),
    EXECUTION_TIME_SECONDS  NUMBER(14,4),
    TEARDOWN_TIME_SECONDS   NUMBER(14,4),
    CPU_SECONDS             NUMBER(16,4),
    ROWS_SCANNED            NUMBER(19),
    BYTES_SCANNED           NUMBER(19),
    TABLES_SCANNED          NUMBER(10),
    PEAK_MEMORY_MB          NUMBER(14,2)
);
ALTER TABLE SPT_SQL_DIAGNOSTIC ADD CONSTRAINT FK_SPT_DIAG_ITER
    FOREIGN KEY (ITERATION_ID) REFERENCES SPT_TUNING_ITERATION (ID);

ALTER TABLE SPT_FEEDBACK ADD (
    ITERATION_ID      NUMBER(19),
    REJECTION_REASON  VARCHAR2(200)
);
ALTER TABLE SPT_FEEDBACK ADD CONSTRAINT FK_SPT_FB_ITER
    FOREIGN KEY (ITERATION_ID) REFERENCES SPT_TUNING_ITERATION (ID);

CREATE TABLE SPT_USER_DIRECTORY (
    USER_ID       VARCHAR2(200)   NOT NULL,
    DISPLAY_NAME  VARCHAR2(200),
    USER_GROUP    VARCHAR2(200),
    DEPARTMENT    VARCHAR2(200),
    ACTIVE        NUMBER(1)       DEFAULT 1 NOT NULL,
    UPDATED_AT    TIMESTAMP       NOT NULL,
    UPDATED_BY    VARCHAR2(100),
    CONSTRAINT PK_SPT_USER_DIRECTORY PRIMARY KEY (USER_ID),
    CONSTRAINT CK_SPT_USERDIR_ACTIVE CHECK (ACTIVE IN (0, 1))
);
CREATE INDEX IX_SPT_USERDIR_GROUP ON SPT_USER_DIRECTORY (USER_GROUP);

CREATE OR REPLACE VIEW SPT_TRACKER_V AS
SELECT t.ID                         AS TRACKER_ID,
       g.ID                         AS GROUP_ID,
       g.GROUP_SIZE,
       g.DISTINCT_USERS,
       g.FINGERPRINT,
       g.AVG_DURATION_MINUTES,
       g.MIN_DURATION_MINUTES,
       g.MAX_DURATION_MINUTES,
       g.TOTAL_DURATION_MINUTES,
       g.FIRST_SEEN,
       g.LAST_SEEN,
       g.SAMPLE_QUERY_SEQ_ID,
       g.SAMPLE_QUERY               AS SAMPLE_QUERY_RAW,
       t.SAMPLE_QUERY_FORMATTED,
       g.ROW_INDICES,
       t.CLEANSED_QUERY,
       t.OPTIMIZED_QUERY,
       t.DEV_TEAM_LEAD,
       t.DEV_TEAM_STATUS,
       t.CLOUDERA_TEAM_LEAD,
       t.SME_TEAM_LEAD,
       t.OPTIMIZED_SQL_STATUS,
       t.CLOUDERA_POST_RUN_VALIDATION,
       t.OG_RUN_DURATION_MINUTES,
       t.POST_RUN_DURATION_MINUTES,
       t.OG_EXECUTION_TIME_SECONDS,
       t.POST_RUN_EXECUTION_TIME_SECONDS,
       t.OG_TEARDOWN_TIME_SECONDS,
       t.POST_RUN_TEARDOWN_TIME_SECONDS,
       t.OG_TEARDOWN_PCT,
       t.POST_RUN_TEARDOWN_PCT,
       t.OG_CPU_SECONDS,
       t.POST_RUN_CPU_SECONDS,
       t.OG_ROWS_SCANNED,
       t.POST_RUN_ROWS_SCANNED,
       t.OG_TABLES_SCANNED,
       t.POST_RUN_TABLES_SCANNED,
       t.THEME,
       t.SME_VALIDATION,
       t.INSTALL_STATUS,
       t.EXECUTE_STATUS,
       t.VALIDATION_STATUS,
       t.CHANGES,
       t.PROBLEM,
       t.RECOMMENDATIONS,
       t.WORKFLOW_STATUS,
       t.PRIORITY,
       t.REQUEST_SOURCE,
       t.REQUESTED_BY,
       t.ENVIRONMENT,
       t.SELECTED_ITERATION_ID,
       t.CREATED_AT,
       t.STAGE_CHANGED_AT,
       t.ADOPTED_AT,
       t.CLOSED_AT,
       t.UPDATED_AT,
       t.UPDATED_BY
  FROM SPT_TUNING_TRACKER t
  JOIN SPT_QUERY_GROUP g ON g.ID = t.GROUP_ID;

