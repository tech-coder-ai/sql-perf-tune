CREATE TABLE SPT_USER_DIRECTORY (
    USER_ID       TEXT PRIMARY KEY,
    DISPLAY_NAME  TEXT,
    USER_GROUP    TEXT,
    DEPARTMENT    TEXT,
    ACTIVE        INTEGER NOT NULL DEFAULT 1 CHECK (ACTIVE IN (0, 1)),
    UPDATED_AT    TIMESTAMP NOT NULL,
    UPDATED_BY    TEXT
);
CREATE INDEX IX_SPT_USERDIR_GROUP ON SPT_USER_DIRECTORY (USER_GROUP);

DROP VIEW SPT_TRACKER_V;
CREATE VIEW SPT_TRACKER_V AS
SELECT t.ID                         AS TRACKER_ID,
       g.ID                         AS GROUP_ID,
       g.GROUP_SIZE,
       g.DISTINCT_USERS,
       g.FINGERPRINT,
       g.AVG_DURATION_MINUTES,
       g.MIN_DURATION_MINUTES,
       g.MAX_DURATION_MINUTES,
       g.TOTAL_DURATION_MINUTES,
       g.FIRST_SEEN,
       g.LAST_SEEN,
       g.SAMPLE_QUERY_SEQ_ID,
       g.SAMPLE_QUERY               AS SAMPLE_QUERY_RAW,
       t.SAMPLE_QUERY_FORMATTED,
       g.ROW_INDICES,
       t.CLEANSED_QUERY,
       t.OPTIMIZED_QUERY,
       t.DEV_TEAM_LEAD,
       t.DEV_TEAM_STATUS,
       t.CLOUDERA_TEAM_LEAD,
       t.SME_TEAM_LEAD,
       t.OPTIMIZED_SQL_STATUS,
       t.CLOUDERA_POST_RUN_VALIDATION,
       t.OG_RUN_DURATION_MINUTES,
       t.POST_RUN_DURATION_MINUTES,
       t.OG_EXECUTION_TIME_SECONDS,
       t.POST_RUN_EXECUTION_TIME_SECONDS,
       t.OG_TEARDOWN_TIME_SECONDS,
       t.POST_RUN_TEARDOWN_TIME_SECONDS,
       t.OG_TEARDOWN_PCT,
       t.POST_RUN_TEARDOWN_PCT,
       t.OG_CPU_SECONDS,
       t.POST_RUN_CPU_SECONDS,
       t.OG_ROWS_SCANNED,
       t.POST_RUN_ROWS_SCANNED,
       t.OG_TABLES_SCANNED,
       t.POST_RUN_TABLES_SCANNED,
       t.THEME,
       t.SME_VALIDATION,
       t.INSTALL_STATUS,
       t.EXECUTE_STATUS,
       t.VALIDATION_STATUS,
       t.CHANGES,
       t.PROBLEM,
       t.RECOMMENDATIONS,
       t.WORKFLOW_STATUS,
       t.PRIORITY,
       t.REQUEST_SOURCE,
       t.REQUESTED_BY,
       t.ENVIRONMENT,
       t.SELECTED_ITERATION_ID,
       t.CREATED_AT,
       t.STAGE_CHANGED_AT,
       t.ADOPTED_AT,
       t.CLOSED_AT,
       t.UPDATED_AT,
       t.UPDATED_BY
  FROM SPT_TUNING_TRACKER t
  JOIN SPT_QUERY_GROUP g ON g.ID = t.GROUP_ID;

