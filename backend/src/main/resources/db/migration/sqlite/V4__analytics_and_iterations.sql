-- =====================================================================
-- V4 (SQLite twin of oracle/V4): analytics & tuning iterations
--   SPT_LOOKUP               admin-editable dropdown values (themes, statuses, reasons, ...)
--   SPT_TUNING_ITERATION     every tuning attempt of a tracker item with its test metrics;
--                            the best one is selected, then adopted (or rejected)
--   SPT_USER_DIRECTORY       user -> user group / department (bad queries by user group)
--   SPT_TUNING_TRACKER       request source (log / proactive UAT / user request), stage
--                            timestamps for turnaround, CPU / rows / tables metrics
--   SPT_SQL_DIAGNOSTIC       iteration link + parsed CPU / rows / tables metrics
--   SPT_FEEDBACK             iteration link + rejection reason
-- =====================================================================

CREATE TABLE SPT_LOOKUP (
    ID            INTEGER PRIMARY KEY AUTOINCREMENT,
    CATEGORY      TEXT    NOT NULL,
    LOOKUP_VALUE  TEXT    NOT NULL,
    SORT_ORDER    INTEGER NOT NULL DEFAULT 0,
    TONE          TEXT,
    ACTIVE        INTEGER NOT NULL DEFAULT 1 CHECK (ACTIVE IN (0, 1)),
    CREATED_AT    TIMESTAMP NOT NULL,
    CONSTRAINT UK_SPT_LOOKUP UNIQUE (CATEGORY, LOOKUP_VALUE)
);

CREATE TABLE SPT_TUNING_ITERATION (
    ID                      INTEGER PRIMARY KEY AUTOINCREMENT,
    TRACKER_ID              INTEGER NOT NULL REFERENCES SPT_TUNING_TRACKER (ID),
    ITERATION_NO            INTEGER NOT NULL,
    SOURCE                  TEXT    NOT NULL CHECK (SOURCE IN ('AI_AGENT', 'MANUAL')),
    OPTIMIZATION_RUN_ID     INTEGER REFERENCES SPT_OPTIMIZATION_RUN (ID),
    OPTIMIZED_SQL           TEXT,
    CHANGE_NARRATIVE        TEXT,
    STATUS                  TEXT    NOT NULL CHECK (STATUS IN ('PROPOSED', 'TESTED', 'FAILED', 'SELECTED', 'ADOPTED', 'REJECTED')),
    RUN_DURATION_MINUTES    NUMERIC,
    EXECUTION_TIME_SECONDS  NUMERIC,
    TEARDOWN_TIME_SECONDS   NUMERIC,
    CPU_SECONDS             NUMERIC,
    ROWS_SCANNED            INTEGER,
    BYTES_SCANNED           INTEGER,
    TABLES_SCANNED          INTEGER,
    PEAK_MEMORY_MB          NUMERIC,
    RESULT_ROW_COUNT        INTEGER,
    RESULT_MATCHES          INTEGER CHECK (RESULT_MATCHES IS NULL OR RESULT_MATCHES IN (0, 1)),
    NOTES                   TEXT,
    TESTED_AT               TIMESTAMP,
    TESTED_BY               TEXT,
    CREATED_AT              TIMESTAMP NOT NULL,
    CREATED_BY              TEXT,
    UPDATED_AT              TIMESTAMP,
    VERSION                 INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT UK_SPT_ITERATION_NO UNIQUE (TRACKER_ID, ITERATION_NO)
);
CREATE INDEX IX_SPT_ITER_TRACKER ON SPT_TUNING_ITERATION (TRACKER_ID);

