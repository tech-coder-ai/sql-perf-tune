ALTER TABLE SPT_TUNING_TRACKER ADD COLUMN EXCEPTION_REASON TEXT;
ALTER TABLE SPT_TUNING_TRACKER ADD COLUMN EXCEPTION_BY TEXT;
ALTER TABLE SPT_TUNING_TRACKER ADD COLUMN EXCEPTION_AT TIMESTAMP;
