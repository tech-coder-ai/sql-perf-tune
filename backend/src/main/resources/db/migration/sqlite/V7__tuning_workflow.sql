ALTER TABLE SPT_TUNING_TRACKER ADD COLUMN AUTO_RUN_MESSAGE TEXT;
ALTER TABLE SPT_TUNING_TRACKER ADD COLUMN NOTIFIED_AT TIMESTAMP;
