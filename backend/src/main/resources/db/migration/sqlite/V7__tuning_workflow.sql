CREATE TABLE SPT_SETTING (
    SETTING_KEY    TEXT      NOT NULL PRIMARY KEY,
    SETTING_VALUE  TEXT,
    UPDATED_AT     TIMESTAMP NOT NULL,
    UPDATED_BY     TEXT
);

CREATE TABLE SPT_NOTIFICATION (
    ID             INTEGER PRIMARY KEY AUTOINCREMENT,
    TRACKER_ID     INTEGER REFERENCES SPT_TUNING_TRACKER (ID),
    KIND           TEXT      NOT NULL,
    RECIPIENTS     TEXT,
    SUBJECT        TEXT      NOT NULL,
    BODY           TEXT,
    STATUS         TEXT      NOT NULL CHECK (STATUS IN ('PENDING', 'SENT', 'LOGGED', 'FAILED', 'DISABLED', 'NO_RECIPIENTS')),
    ERROR_MESSAGE  TEXT,
    CREATED_AT     TIMESTAMP NOT NULL,
    SENT_AT        TIMESTAMP
);
CREATE INDEX IX_SPT_NOTIF_TRACKER ON SPT_NOTIFICATION (TRACKER_ID);

CREATE TABLE SPT_THEME_FIX (
    ID             INTEGER PRIMARY KEY AUTOINCREMENT,
    THEME          TEXT      NOT NULL,
    NOTES          TEXT,
    ITEMS_RETRIED  INTEGER   NOT NULL DEFAULT 0,
    RELEASED_AT    TIMESTAMP NOT NULL,
    RELEASED_BY    TEXT
);

